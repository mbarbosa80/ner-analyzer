def build_teap(out_path: str) -> str:
    wb = openpyxl.Workbook()

    ws = wb.active
    ws.title = "Overview (READ ME)"
    ws["A1"] = "Overview"
    ws["A3"] = "Release date:"
    ws["B3"] = "SYNTHETIC — demonstration data only"

    ws = wb.create_sheet("TEAP v2.0")
    ws["A1"] = "TEAP v2.0 / Master Allocation Plan"        # deliberately not the header row
    headers = ["Unique ID", "Venue Code", "Venue Name", "Venue Type", "Zone", "FA Code",
               "Space Code", "Space Name", "Product Code", "Product Description",
               "FINAL QTY", "Primary Product Category", "Network Ports", "Comments"]
    ws.append([])                                          # row 2 will hold the headers
    for i, h in enumerate(headers, start=1):
        ws.cell(row=2, column=i, value=h)
    ports = {p[0]: p[3] for p in PRODUCTS}
    cats = {p[0]: p[2] for p in PRODUCTS}
    names = {p[0]: p[1] for p in PRODUCTS}
    for n, (code, name, fa, pcode, qty) in enumerate(ALLOCATIONS, start=1):
        ws.append([f"ID{n:08d}", "SYN", "Synthetic Venue", "Competition", "Demo Zone",
                   fa, code, name, pcode, names[pcode], qty, cats[pcode],
                   qty * ports[pcode], ""])

    ws = wb.create_sheet("Products")
    ws["A1"] = "Product Catalogue"
    ws.append([])
    for i, h in enumerate(["Service Category", "Primary Product Category", "Product Code",
                           "Product Name", "Product Description", "Network Ports"], start=1):
        ws.cell(row=3, column=i, value=h)
    for code, name, cat, prt in PRODUCTS:
        ws.append(["IT", cat, code, name, name, prt])

    ws = wb.create_sheet("Venues")
    ws.append(["Venue Code", "Venue Name", "Venue Type", "Zone"])
    ws.append(["SYN", "Synthetic Venue", "Competition", "Demo Zone"])

    wb.save(out_path)
    return out_path


def build_all(out_dir: str = "sample_data") -> dict[str, str]:
    os.makedirs(out_dir, exist_ok=True)
    pdf = build_pdf(os.path.join(out_dir, "synthetic_venue_plan.pdf"))
    scanned = build_scanned_pdf(pdf, os.path.join(out_dir, "synthetic_venue_scanned.pdf"))
    teap = build_teap(os.path.join(out_dir, "synthetic_teap.xlsx"))
    return {"pdf": pdf, "scanned_pdf": scanned, "teap": teap}


