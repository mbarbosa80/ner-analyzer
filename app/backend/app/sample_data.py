def _draw_page(page: pymupdf.Page, rooms: list[Room], markers, level_label: str,
               scale_text: str) -> None:
    page.draw_rect(pymupdf.Rect(40, 40, PAGE_W - 40, PAGE_H - 40),
                   color=(0.2, 0.2, 0.2), width=1.2)
    page.insert_text((60, 80), "SYNTHETIC VENUE — VVO", fontsize=20, color=(0, 0, 0))
    page.insert_text((60, 104), level_label, fontsize=13, color=(0, 0, 0))
    page.insert_text((60, PAGE_H - 78), scale_text, fontsize=11, color=(0, 0, 0))
    page.insert_text((60, PAGE_H - 60), TITLE_BLOCK.splitlines()[0], fontsize=7,
                     color=(0.4, 0.4, 0.4))

    # legend
    lx, ly = PAGE_W - 380, 80
    page.insert_text((lx, ly), "LEGEND", fontsize=10, color=(0, 0, 0))
    for i, (txt, col) in enumerate((("TER", BLUE), ("NER - Critical", RED),
                                    ("NER - Non critical", YELLOW),
                                    ("Proposed NER", (0.5, 0.0, 0.6)))):
        y = ly + 16 + i * 14
        page.draw_circle((lx + 6, y - 3), 4, color=col, fill=col)
        page.insert_text((lx + 18, y), txt, fontsize=8, color=(0, 0, 0))

    for r in rooms:
        rect = pymupdf.Rect(r.x, r.y, r.x + r.w, r.y + r.h)
        page.draw_rect(rect, color=(0.25, 0.25, 0.25), width=0.8)
        page.insert_text((r.x + 4, r.y + 14), f"{r.area_m2} m²", fontsize=7,
                         color=(0.3, 0.3, 0.3))
        page.insert_text((r.x + 4, r.y + 25), r.name[:34], fontsize=7.5, color=(0, 0, 0))
        page.insert_text((r.x + 4, r.y + 35), r.code, fontsize=7.5, color=(0, 0, 0))

    for label, pg, x, y, col, _crit in markers:
        page.draw_circle((x, y), 6, color=col, fill=col)
        page.insert_text((x + 10, y + 3), label, fontsize=9, color=col)


def build_pdf(out_path: str) -> str:
    doc = pymupdf.open()
    p1 = doc.new_page(width=PAGE_W, height=PAGE_H)
    _draw_page(p1, ROOMS_L1, [m for m in MARKERS if m[1] == 1],
               "LEVEL 100 — COMPETITION", "SCALE 1 : 200")
    p2 = doc.new_page(width=PAGE_W, height=PAGE_H)
    _draw_page(p2, ROOMS_L2, [m for m in MARKERS if m[1] == 2],
               "LEVEL 200 — MEDIA", "SCALE 1 : 200")
    p3 = doc.new_page(width=PAGE_W, height=PAGE_H)
    p3.insert_text((60, 80), "KEY PLAN", fontsize=18)
    p3.insert_text((60, 110), '1/8" = 1\'-0"', fontsize=11)
    p3.draw_rect(pymupdf.Rect(200, 200, 900, 700), color=(0.3, 0.3, 0.3), width=1)
    doc.save(out_path)
    doc.close()
    return out_path


def build_scanned_pdf(vector_pdf: str, out_path: str, dpi: int = 55) -> str:
    """A raster-only copy of page 1, to exercise the OCR-required path."""
    src = pymupdf.open(vector_pdf)
    pix = src[0].get_pixmap(dpi=dpi)
    dst = pymupdf.open()
    page = dst.new_page(width=src[0].rect.width, height=src[0].rect.height)
    page.insert_image(page.rect, pixmap=pix)
    dst.save(out_path)
    src.close()
    dst.close()
    return out_path


